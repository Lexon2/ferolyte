// Vanilla texture atlas keys and behavior pack loot table paths (keys / paths only) from the pinned bedrock-samples, for the reference checks: a project
// `terrain_texture.json` / `item_texture.json` only lists its own keys, vanilla ones (`stone`, `planks`, `apple`) must not be reported.
//   node scripts/schemas/vanilla-texture-keys.mjs          writes packages/cli/compiler/registry/vanilla-texture-keys.generated.ts
//   node scripts/schemas/vanilla-texture-keys.mjs --check  fails when the committed file is out of date (used by the test)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { parse } from 'jsonc-parser';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SAMPLES = path.join(ROOT, '.cache/bedrock-samples/resource_pack/textures');
const LOOT = path.join(ROOT, '.cache/bedrock-samples/behavior_pack/loot_tables');
const OUT = path.join(ROOT, 'packages/cli/compiler/registry/vanilla-texture-keys.generated.ts');

/** Paths of the vanilla loot tables relative to the pack (`loot_tables/empty.json`), sorted. */
const lootTablePaths = (dir = LOOT, prefix = 'loot_tables') =>
  readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? lootTablePaths(path.join(dir, entry.name), `${prefix}/${entry.name}`)
        : entry.name.endsWith('.json')
          ? [`${prefix}/${entry.name}`]
          : [],
    )
    .sort();

export const render = () => {
  const keys = (file) =>
    Object.keys(parse(readFileSync(path.join(SAMPLES, file), 'utf8')).texture_data).sort();
  const list = (name, items) =>
    `export const ${name}: readonly string[] = [\n${items.map((k) => `  ${JSON.stringify(k)},`).join('\n')}\n];\n`;

  return [
    '// GENERATED by scripts/schemas/vanilla-texture-keys.mjs from Mojang/bedrock-samples — do not edit.',
    '// Keys of the vanilla `terrain_texture.json` and `item_texture.json`, paths of the vanilla behavior pack loot tables (keys / paths only).',
    '',
    list('VANILLA_TERRAIN_TEXTURE_KEYS', keys('terrain_texture.json')),
    list('VANILLA_ITEM_TEXTURE_KEYS', keys('item_texture.json')),
    list('VANILLA_LOOT_TABLE_PATHS', lootTablePaths()),
  ].join('\n');
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!existsSync(SAMPLES)) {
    console.error('Samples missing: run `node scripts/schemas/fetch-samples.mjs` first');
    process.exit(1);
  }
  const text = render();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('vanilla-texture-keys.generated.ts is out of date: run `npm run schemas:vanilla-keys`');
      process.exit(1);
    }
    console.log('vanilla texture keys are up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)}`);
  }
}
